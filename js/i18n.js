const i18nManager = {
  current: 'pt',
  init() {
    const saved = localStorage.getItem('cosmos-lang');
    if (saved && (saved === 'pt' || saved === 'en')) {
      this.current = saved;
    } else {
      const browserLang = navigator.language.toLowerCase().substring(0, 2);
      this.current = browserLang === 'en' ? 'en' : 'pt';
    }
    this.apply();
    this.updateToggle();
  },
  toggle() {
    this.current = this.current === 'pt' ? 'en' : 'pt';
    localStorage.setItem('cosmos-lang', this.current);
    this.apply();
    this.updateToggle();
    if (window.renderPortfolio) window.renderPortfolio();
    if (window.renderCatalogue) window.renderCatalogue();
    if (window.renderShop) window.renderShop();
    if (window.renderExhibitions) window.renderExhibitions();
  },
  t(key) { return I18N[this.current][key] || key; },
  apply() {
    document.documentElement.lang = this.current;
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const translation = this.t(key);
      if (translation) el.textContent = translation;
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      const translation = this.t(key);
      if (translation) el.placeholder = translation;
    });
    const heroRole = document.querySelector('[data-bio-role]');
    if (heroRole && window.BIO) heroRole.textContent = BIO.role[this.current];
    const heroTagline = document.querySelector('[data-bio-tagline]');
    if (heroTagline && window.BIO) heroTagline.textContent = BIO.tagline[this.current];
  },
  updateToggle() {
    const toggle = document.getElementById('lang-toggle');
    if (toggle) {
      toggle.textContent = this.current === 'pt' ? 'EN' : 'PT';
      toggle.setAttribute('aria-label', this.current === 'pt' ? 'Switch to English' : 'Mudar para Português');
    }
  },
  get lang() { return this.current; }
};

if (typeof window !== 'undefined') {
  window.i18n = i18nManager;
  window.t = (key) => i18nManager.t(key);
}
